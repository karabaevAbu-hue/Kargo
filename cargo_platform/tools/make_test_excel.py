"""Создаёт testdata/sklad_test_20.xlsx — файл «склада» на 20 строк с намеренными ошибками.

    python -m cargo_platform.tools.make_test_excel

Рассчитан на карго с префиксом кода TST и тремя клиентами TST-0001…TST-0003.
Подробности — docs/LIVE_TEST_CHECKLIST.md.
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font

HEADER = ["Код клиента", "Трек-номер", "Вес (кг)", "Количество мест", "Описание"]
ROWS = [
    # коды в разном написании — все означают один код
    ["TST-0001", "TRK10000001", "1,2", 1, "Кроссовки"],           # 1  вес с запятой; этот трек клиент добавил сам
    ["tst 1", "TRK10000002", 0.8, 1, "Футболки"],                   # 2  «tst 1» = TST-0001
    ["TST0001", "TRK10000003", 2.5, 1, "Куртка"],                   # 3  «TST0001» = TST-0001
    ["TST-0002", "TRK10000004", 3.1, 1, "Чайник"],                  # 4
    ["TST-0002", "TRK10000005", 0.5, 1, "Кружки"],                  # 5
    ["0002", "TRK10000006", 1.75, 1, "Лампа"],                      # 6  только номер → префикс подставится
    ["TST-0003", "TRK10000007", 4, 1, "Сумка"],                     # 7
    ["TST-0003", "TRK10000008", 2, 1, "Платье"],                    # 8
    ["TST-0003", "TRK10000009", 1.1, 1, "Чехол"],                   # 9
    ["TST-0001", "TRK10000001", 0.6, 1, "Кроссовки (второе место)"],  # 10 ТОТ ЖЕ трек, что в строке 1 → одна посылка, 2 места
    ["TST-0099", "TRK10000011", 1.0, 1, "Игрушка"],                 # 11 такой код не выдан → «Неопознанные»
    ["TSZ-0001", "TRK10000012", 1.4, 1, "Часы"],                    # 12 ошибка в префиксе → «Неопознанные», подсказка TST-0001
    ["", "TRK10000013", 1.0, 1, "Шапка"],                           # 13 кода нет, но трек добавил клиент → найдётся по треку
    ["", "TRK10000014", 0.9, 1, "Перчатки"],                        # 14 кода нет и трек никто не добавлял → «Неопознанные»
    ["TST-0002", "TRK10000015", "abc", 1, "Без веса"],              # 15 вес не число → «Без веса»
    ["TST-0001", "TRK10000016", 1.0, 2, "Коробка 2 места"],         # 16 в колонке «мест» = 2
    ["tst-0003", "TRK10000017", 0.9, 1, "Ремень"],                  # 17 нижний регистр
    ["TST-0002", "TRK10000018", 5.0, 1, "Блендер"],                 # 18
    ["TST-0004", "TRK10000019", 1.0, 1, "Коврик"],                  # 19 четвёртого клиента нет → «Неопознанные»
    ["TST-0001", "TRK10000020", 1.3, 1, "Книги"],                   # 20
]


def build(path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Склад"
    ws.append(HEADER)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in ROWS:
        ws.append(r)
    for col, width in zip("ABCDE", (14, 16, 10, 16, 28)):
        ws.column_dimensions[col].width = width
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)


if __name__ == "__main__":
    out = Path(__file__).resolve().parent.parent / "testdata" / "sklad_test_20.xlsx"
    build(out)
    print(f"Создан {out} ({len(ROWS)} строк)")
