def ct(lang: str | None, key: str, **kw) -> str:
    table = KY if lang == "ky" else RU
    text = table.get(key) or RU.get(key, key)
    return text.format(**kw) if kw else text


def variants(key: str) -> set[str]:
    return {RU[key], KY.get(key, RU[key])}
